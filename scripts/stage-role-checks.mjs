const files = readdirSync(PHONE).filter((f) => f.endsWith(".js"));
for (const [name, c] of Object.entries(CASES)) {
  const dir = join(home, "mods", `phone-chk-${name}`);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "mod.json"), '{"place":"none"}\n');
  writeFileSync(join(dir, "fake-herdr.js"), fixture(c));
  for (const f of files) writeFileSync(join(dir, f), readFileSync(join(PHONE, f), "utf8").replaceAll('from "herdr"', 'from "./fake-herdr.js"'));
}
